export interface Change {
  path: string
  kind: 'added' | 'changed' | 'removed'
}

/**
 * Make `into` hold `read(path)` for every listed path, and report what moved.
 * `read` answers null for a path the source no longer has, which is deleted
 * in the copy. Nothing off the list is read, written or deleted.
 */
export function mirror(read: (file: string) => Buffer | null, into: string, list: readonly string[] = MIRROR): Change[] {
  const refused = list.filter((file) => isExcluded(file) || PUBLIC_OWN.includes(file))
  if (refused.length > 0) throw new Error(`the mirror list holds what the public copy must not: ${refused.join(', ')}`)
  const changes: Change[] = []
  for (const file of list) {
    const target = path.join(into, file)
    const wanted = read(file)
    const present = existsSync(target)
    if (wanted === null) {
      if (present) {
        rmSync(target)
        changes.push({ path: file, kind: 'removed' })
      }
      continue
    }
    if (present && readFileSync(target).equals(wanted)) continue
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, wanted)
    changes.push({ path: file, kind: present ? 'changed' : 'added' })
  }
  return changes
}

/** A command, run in a directory; injected so the test can see what `--pr` would run without running it. */
export type Run = (command: string, args: readonly string[], cwd: string) => string

const run: Run = (command, args, cwd) =>
  execFileSync(command, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 256 * 1024 * 1024 })

/**
 * Commit the changes on a branch of the clone, push it, and open the PR in
 * the public repository. Paths are staged one by one, never `add -A`: a file
 * somebody left in the clone is not part of the mirror.
 */
export function openPullRequest(into: string, changes: readonly Change[], sha: string, execute: Run = run): string {
  const branch = `mirror/${sha.slice(0, 12)}`
  execute('git', ['checkout', '-b', branch], into)
  const removed = changes.filter((change) => change.kind === 'removed').map((change) => change.path)
  const written = changes.filter((change) => change.kind !== 'removed').map((change) => change.path)
  if (written.length > 0) execute('git', ['add', '--', ...written], into)
  if (removed.length > 0) execute('git', ['rm', '--cached', '--quiet', '--', ...removed], into)
  const message = `Mirror ${sha.slice(0, 12)} of the private repository\n\n${summary(changes)}`
  execute('git', ['commit', '-m', message], into)
  execute('git', ['push', '-u', 'origin', branch], into)
  return execute('gh', ['pr', 'create', '--repo', PUBLIC_REPO, '--head', branch, '--title', `Mirror ${sha.slice(0, 12)}`, '--body', message], into).trim()
}

export function summary(changes: readonly Change[]): string {
  if (changes.length === 0) return 'Nothing changed.'
  return changes.map((change) => `${change.kind.padEnd(7)} ${change.path}`).join('\n')
}

/** `--into <dir>`, `--pr`, `--ref <ref>`; anything else is refused rather than ignored. */
export function parseArgs(argv: readonly string[]): { into: string; pr: boolean; ref: string | null } {
  let into: string | null = null
  let pr = false
  let ref: string | null = null
  for (let at = 0; at < argv.length; at += 1) {
    const arg = argv[at]
    if (arg === '--pr') pr = true
    else if (arg === '--into' || arg === '--ref') {
      const value = argv[at + 1]
      if (value === undefined || value.startsWith('--')) throw new Error(`${arg} needs a value`)
      if (arg === '--into') into = value
      else ref = value
      at += 1
    } else throw new Error(`unknown argument ${arg}`)
  }
  if (into === null) throw new Error('--into <clone of the public repository> is required')
  return { into, pr, ref }
}

function main(): void {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
  const { into, pr, ref: given } = parseArgs(process.argv.slice(2))
  // The clone has to be the public repository: a mistyped path pointing at a
  // checkout of anything else would have the list copied over it, and --pr
  // would push it.
  const origin = run('git', ['remote', 'get-url', 'origin'], into).trim()
  if (!origin.replace(/\.git$/, '').endsWith(PUBLIC_REPO)) throw new Error(`${into} is a clone of ${origin}, not ${PUBLIC_REPO}`)
  if (given === null) run('git', ['fetch', '--quiet', 'origin', 'main'], root)
  const ref = given ?? 'origin/main'
  const sha = run('git', ['rev-parse', ref], root).trim()
  const tracked = new Set(run('git', ['ls-tree', '-r', '--name-only', ref], root).split('\n'))
  const read = (file: string): Buffer | null =>
    tracked.has(file) ? execFileSync('git', ['show', `${ref}:${file}`], { cwd: root, maxBuffer: 256 * 1024 * 1024 }) : null
  const changes = mirror(read, path.resolve(into))
  console.log(`${ref} at ${sha.slice(0, 12)}, ${MIRROR.length} paths listed:\n${summary(changes)}`)
  if (!pr) return
  if (changes.length === 0) {
    console.log('Nothing to open a pull request for.')
    return
  }
  console.log(openPullRequest(path.resolve(into), changes, sha))
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
